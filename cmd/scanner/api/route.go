func SetupGinRouter(
	scannerSvc component.ScannerSrv,
	imageSvc map[string]imagemeta.ImageService,
	rejectSvc component.ImageRejectSrv,
	harborSvc component.HarborSvc,
	registrySrv component.RegistrySrvInterface,
	scanConfigSrv component.ScanConfigSrvInterface,
	vuluSrv component.VulnServiceInterface,
	syncImageSrv component.SyncImageInterface,
	ciDalSrv ci.CiComponent,
	scannerInfo component.ScannerInstanceInfoInterface,
	webshellSrv scanwebshell.WebshellController,
	exportSrv scanReportService.ExportTaskInterface,
	dbManageSrv dbManage.DBManageSrv,
	policySrv imagesecSrv.SecurityPolicyService,
	scanTaskSrv imagescan.ScanTaskService,
	sensitiveRuleService imagesecSrv.SensitiveRuleService,
	scanImageConfigService imagesecSrv.ScanImageConfigService,
	nodeVulnSrv imagesecSrv.VulnService,
	webshellService imagesecSrv.WebshellService,
	nodeSrv imagesecSrv.NodeReportService,
) *gin.Engine {

	router := gin.Default()
	router.MaxMultipartMemory = 2 << 20

	router.Use(gin.Logger(), gin.Recovery(), AddLanguage)

	router.GET("/health", func(c *gin.Context) {
		c.JSON(200, gin.H{
			"message": "healthy",
		})
	})

	router = WebAPI(
		router,
		scannerSvc,
		imageSvc,
		rejectSvc,
		harborSvc,
		registrySrv,
		scanConfigSrv,
		vuluSrv,
		syncImageSrv,
		ciDalSrv,
		scannerInfo,
		webshellSrv,
		exportSrv,
		dbManageSrv,
		policySrv,
		scanTaskSrv,
		sensitiveRuleService,
		scanImageConfigService,
		nodeVulnSrv,
		webshellService,
		nodeSrv,
	)
	router = OpenAPI(router, scannerSvc, rejectSvc, registrySrv, scanConfigSrv,
		vuluSrv, ciDalSrv, imageSvc[imagesecModel.ImageFromRegistry], syncImageSrv, exportSrv)

	return router
}

