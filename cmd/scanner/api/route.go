func SetupGinRouter(redisClient *redis.Client,
	scannerSvc component.ScannerSrv,
	imageSvc component.ImageSrvInterface,
	rejectSvc component.ImageRejectSrv,
	harborSvc component.HarborSvc,
	registrySrv component.RegistrySrvInterface,
	scanConfigSrv component.ScanConfigSrvInterface,
	vuluSrv component.VulnServiceInterface,
	syncImageSrv component.SyncImageInterface,
	ciDalSrv ci.CiComponent,
	scannerInfo component.ScannerInstanceInfoInterface,
	imageScanResult component.ScanResultInterface,
) *gin.Engine {

	router := gin.Default()
	router.MaxMultipartMemory = 2 << 20

	router.Use(gin.Logger(), gin.Recovery())

	router.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	router.GET("/health", func(c *gin.Context) {
		c.JSON(200, gin.H{
			"message": "healthy",
		})
	})

	router = WebAPI(
		router,
		scannerSvc,
		imageSvc,
		rejectSvc,
		harborSvc,
		registrySrv,
		scanConfigSrv,
		vuluSrv,
		syncImageSrv,
		ciDalSrv,
		scannerInfo,
		imageScanResult,
	)
	router = OpenAPI(router, scannerSvc, rejectSvc, registrySrv, scanConfigSrv, vuluSrv, ciDalSrv, imageSvc, syncImageSrv)

	return router
}

