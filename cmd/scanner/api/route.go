package api

import (
	"context"

	"github.com/go-chi/chi"
	httpSwagger "github.com/swaggo/http-swagger"
	"go.mongodb.org/mongo-driver/mongo"

	"gitlab.com/piccolo_su/vegeta/cmd/scanner/component"
	_ "gitlab.com/piccolo_su/vegeta/cmd/scanner/docs" // docs is generated by Swag CLI
	"gitlab.com/piccolo_su/vegeta/pkg/logging"
	"gitlab.com/piccolo_su/vegeta/pkg/response"
)

var (
	log *logging.Logger
)

func init() {
	log = logging.GetLogger()
}

// SetupRoutes is to set up the chi router
func SetupRoutes(
	ctx context.Context,
	r *chi.Mux,
	redclair *component.RedClairService,
	harbor *component.HarborRESTClient,
	mongodb *mongo.Database,
) {
	log.Debug().Msg("setting up routes...")

	r.Get("/ping", response.Pong)
	r.Get("/swagger/*", httpSwagger.Handler(httpSwagger.URL("swagger/doc.json")))

	api := newAPI(ctx, redclair, harbor, mongodb)
	r.Route("/api", func(r chi.Router) {
		r.Route("/v1", func(r chi.Router) {
			r.Route("/scan", api.scan())
		})
	})
}
